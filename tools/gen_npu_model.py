#!/usr/bin/env python3
"""把 Vela 编译出的 NPU 模型转成固件内嵌的 C 数组。

用法:
    python tools/gen_npu_model.py tools/vela_out/yamnet_cal_vela.tflite

产物:
    Edgi_Talk_M55_XiaoZhi/applications/snore_model_npu.c/.h

为什么要单独一份而不是覆盖 snore_model_data.c：
    原 CPU 版是回退路径。NPU 版链接失败或真机不支持时可以立刻切回去，
    不必重新跑 Vela（Vela 需要特定 Python 环境，不在 Studio 里）。
"""
import os
import sys

ARRAY_NAME = "snore_model_npu"
MAX_BYTES_PER_LINE = 16


def emit_c(data, out_path, hdr_path):
    n = len(data)

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Auto-generated by tools/gen_npu_model.py - do not edit.\n")
        f.write(" * Source: Vela-compiled Ethos-U55 model (128 MACs/cc, Sram_Only).\n")
        f.write(" * All operators are scheduled on the NPU (no CPU fallback).\n")
        f.write(" */\n")
        f.write('#include "%s.h"\n\n' % ARRAY_NAME)
        f.write("const unsigned char %s[%s] __attribute__((aligned(16))) = {\n"
                % (ARRAY_NAME, "SNORE_MODEL_NPU_SIZE"))
        for i in range(0, n, MAX_BYTES_PER_LINE):
            chunk = data[i:i + MAX_BYTES_PER_LINE]
            f.write("".join("0x%02x," % b for b in chunk))
            f.write("\n")
        f.write("};\n")

    guard = ARRAY_NAME.upper() + "_H"
    with open(hdr_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Auto-generated by tools/gen_npu_model.py - do not edit. */\n")
        f.write("#ifndef %s\n#define %s\n\n" % (guard, guard))
        f.write("#include <stddef.h>\n\n")
        f.write("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
        f.write("#define SNORE_MODEL_NPU_SIZE %du\n" % n)
        f.write("extern const unsigned char %s[SNORE_MODEL_NPU_SIZE];\n\n" % ARRAY_NAME)
        f.write("#ifdef __cplusplus\n}\n#endif\n\n#endif\n")


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 1

    src = argv[1]
    if not os.path.isfile(src):
        print("not found:", src)
        return 1

    data = open(src, "rb").read()
    if data[:4] != b"TFL3":
        print("warning: file does not start with TFL3 magic")
    if b"ethos-u" not in data:
        print("ERROR: no 'ethos-u' custom op found - this is NOT an NPU model")
        return 1

    app_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                           "Edgi_Talk_M55_XiaoZhi", "applications")
    out_c = os.path.join(app_dir, ARRAY_NAME + ".c")
    out_h = os.path.join(app_dir, ARRAY_NAME + ".h")

    emit_c(data, out_c, out_h)

    print("model size : %d bytes (%.2f MB)" % (len(data), len(data) / 1048576.0))
    print("ethos-u op : %d" % data.count(b"ethos-u"))
    print("wrote      :", out_c)
    print("wrote      :", out_h)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
